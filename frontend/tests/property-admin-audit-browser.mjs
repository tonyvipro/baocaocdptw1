import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || '../node_modules/.audit-browser/node_modules/playwright');
const base = process.env.AUDIT_BASE_URL || 'http://127.0.0.1:3101';
const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1365, height: 1000 } });
  page.setDefaultTimeout(30000);
  const user = { id: 90001, role_id: 1, name: 'Audit Admin', is_active: true };
  let row = { id: 101, code: 'AUDIT-ADMIN', title: 'Tin kiểm tra quản trị', user_id: user.id, type: 'Loại mới từ SQL', purpose: 'sale', status: 1, price: 2e9, price_sale_text: '2 tỷ', area: 80, bedrooms: 2, bathrooms: 2, address: 'Địa chỉ thử nghiệm', city: 'TP. Hồ Chí Minh', expire_date: '2027-01-01T00:00:00Z' };
  const writes = [], errors = [];
  let failUpdate = true;
  page.on('pageerror', error => errors.push(error.message));
  page.on('dialog', dialog => dialog.accept());
  await page.addInitScript(user => { localStorage.setItem('3tv_user', JSON.stringify(user)); localStorage.setItem('3tv_token', 'mock-api-only'); }, user);
  await page.route('**/api/**', async route => {
    const request = route.request(), url = new URL(request.url()), path = url.pathname;
    let data = {};
    if (request.method() !== 'GET') {
      const body = request.postDataJSON();
      writes.push({ path, method: request.method(), body });
      assert.ok(path.startsWith('/api/properties'), `Unexpected mocked write: ${path}`);
      if (request.method() === 'PUT') {
        if (failUpdate) return route.fulfill({ status: 422, json: { message: 'Lỗi kiểm tra: địa chỉ quá dài.' } });
        row = { ...row, ...body, status: Number(body.status) };
      } else if (path.endsWith('/status')) row.status = body.status;
      else if (path.endsWith('/extend')) row.expire_date = '2027-01-31T00:00:00Z';
      else if (path.endsWith('/restore')) row.deleted_at = null;
      else if (request.method() === 'DELETE') row.deleted_at = new Date().toISOString();
      else if (request.method() === 'POST' && path === '/api/properties') return route.fulfill({ status: 422, json: { message: 'Lỗi kiểm tra: giá vượt giới hạn.' } });
      return route.fulfill({ json: { data: row, message: 'Thành công.' } });
    }
    const paginated = rows => ({ data: rows, meta: { total: rows.length, current_page: 1, last_page: 1, per_page: 12 } });
    if (path === '/api/me') data = { user };
    if (path === '/api/properties') data = url.searchParams.get('admin') ? paginated(row.deleted_at ? [] : [row]) : [row];
    if (path === '/api/properties/trash') data = paginated(row.deleted_at ? [row] : []);
    if (path.endsWith('/stats')) data = { total: 1, active: row.status === 1 ? 1 : 0, hidden: row.status === 4 ? 1 : 0, pending: 0, trash: row.deleted_at ? 1 : 0 };
    if (path === '/api/property-types') data = { data: [{ id: 1, name: 'Loại mới từ SQL', status: 1 }] };
    if (path.endsWith('-history')) data = { data: [] };
    if (path.includes('notifications')) data = { data: [], unread_count: 0 };
    return route.fulfill({ json: data });
  });
  await page.route(/https:\/\/(?!127\.0\.0\.1|localhost)/, route => route.fulfill({ body: '' }));
  await page.goto(base + '/#admin/properties', { waitUntil: 'domcontentloaded', timeout: 120000 });
  await page.getByTitle('Chỉnh sửa thông tin', { exact: true }).waitFor();
  await page.getByTitle('Chỉnh sửa thông tin', { exact: true }).click();
  const form = page.locator('form').filter({ has: page.locator('input[name="title"]') });
  assert.equal(await form.locator('input[name="title"]').getAttribute('maxLength'), '255');
  assert.ok((await form.locator('select[name="type"]').innerText()).includes('Loại mới từ SQL'));
  await form.locator('input[name="title"]').fill('Tin đã sửa qua giao diện');
  await page.getByRole('button', { name: 'Cập nhật thông tin', exact: true }).click();
  await page.getByText('Lỗi kiểm tra: địa chỉ quá dài.', { exact: true }).waitFor();
  assert.equal(writes.length, 1, 'A 422 response must not trigger a second write to port 8080');
  failUpdate = false;
  await page.getByRole('button', { name: 'Cập nhật thông tin', exact: true }).click();
  await form.waitFor({ state: 'detached' });
  assert.equal(row.title, 'Tin đã sửa qua giao diện');
  await page.getByTitle('Tạm ẩn bài đăng', { exact: true }).click();
  await page.getByTitle('Bật hiển thị', { exact: true }).waitFor();
  assert.equal(row.status, 4);
  await page.getByTitle('Bật hiển thị', { exact: true }).click();
  await page.getByTitle('Tạm ẩn bài đăng', { exact: true }).waitFor();
  assert.equal(row.status, 1);
  await page.getByTitle('Gia hạn thời gian hiển thị', { exact: true }).click();
  await page.getByRole('button', { name: /Xác Nhận Gia Hạn/ }).click();
  await page.waitForTimeout(500);
  assert.ok(writes.some(write => write.path.endsWith('/extend') && write.body.days === 30));
  await page.goto(base + '/#admin/properties', { waitUntil: 'domcontentloaded' });
  await page.getByTitle('Chuyển vào Thùng rác', { exact: true }).click();
  await page.getByRole('button', { name: /Thùng rác/ }).first().click();
  await page.getByRole('button', { name: 'Khôi phục', exact: true }).first().click();
  await page.waitForTimeout(500);
  assert.equal(row.deleted_at, null);
  await page.getByRole('button', { name: /Thêm BĐS mới/ }).click();
  const create = page.locator('form').filter({ has: page.locator('input[name="title"]') });
  await create.locator('input[name="title"]').fill('Tin mới kiểm tra');
  await create.locator('select[name="type"]').selectOption('Loại mới từ SQL');
  await create.locator('input[name="price"]').fill('2000000000');
  await create.locator('input[name="area"]').fill('80');
  await create.locator('input[name="address"]').fill('Địa chỉ thử nghiệm');
  const beforeCreate = writes.length;
  await page.getByRole('button', { name: 'Đăng tin mới', exact: true }).click();
  await page.getByText('Lỗi kiểm tra: giá vượt giới hạn.', { exact: true }).waitFor();
  assert.equal(writes.length, beforeCreate + 1);
  assert.equal(writes.at(-1).body.type, 'Loại mới từ SQL');
  assert.deepEqual(errors, []);
  console.log('PASS: admin create/edit, dynamic SQL types, title length, 422 without duplicate write, hide/show, 30-day extension, delete and restore. Mocked API only.');
} finally { await browser.close(); }
